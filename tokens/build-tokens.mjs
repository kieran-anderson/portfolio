#!/usr/bin/env node
/**
 * build-tokens.mjs — turns tokens/figma-variables.json (exported from Figma) into CSS.
 *
 * Outputs (both GENERATED — never edit by hand):
 *   src/styles/tokens.css          Plain CSS custom properties. Works with or without Tailwind.
 *                                  Light, dark (class or system), and Mobile/Tablet/Desktop values.
 *   src/styles/tailwind-theme.css  Tailwind v4 @theme: registers ONLY our tokens as utilities
 *                                  (bg-surface-default, p-16, text-h1, rounded-full, tablet:…).
 *
 * No dependencies on purpose: runs with plain Node (>=18). `npm run tokens`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(resolve(root, "tokens/figma-variables.json"), "utf8"));
const header = `/* GENERATED by tokens/build-tokens.mjs from tokens/figma-variables.json (Figma ${src.source.fileKey}, exported ${src.source.exportedAt}). DO NOT EDIT. */\n`;

const col = (name) => {
  const c = src.collections.find((c) => c.name === name);
  if (!c) throw new Error(`Missing collection ${name}`);
  return c;
};
const byName = new Map(src.collections.flatMap((c) => c.variables.map((v) => [v.name, v])));
const cssName = (figmaName) => {
  const v = byName.get(figmaName);
  if (!v) throw new Error(`Unknown variable ${figmaName}`);
  return v.css;
};

/** Format a value as CSS. Aliases become var(--other). */
function cssValue(v, raw) {
  if (raw && typeof raw === "object" && raw.alias) return `var(${cssName(raw.alias)})`;
  if (v.type === "COLOR") return raw;
  if (v.type === "STRING") return /^[a-z-]+\(/.test(raw) ? raw : JSON.stringify(raw);
  if (v.type === "FLOAT") {
    if (v.unitless) return String(raw);
    if (v.name.startsWith("duration/")) return `${raw}ms`;
    return `${raw}px`;
  }
  return String(raw);
}
const decl = (v, raw) => `  ${v.css}: ${cssValue(v, raw)};${v.description ? ` /* ${v.description.replace(/\*\//g, "")} */` : ""}`;
const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}\n`;
const indent = (s) => s.split("\n").map((l) => (l ? "  " + l : l)).join("\n");

const prim = col("Primitives");
const color = col("Color");
const resp = col("Responsive");
const bp = src.breakpoints;
const lightLines = color.variables.map((v) => decl(v, v.values.Light));
const darkLines = color.variables.map((v) => decl(v, v.values.Dark));

// Effects → shadows
const rgba = (hex, a) => {
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${a})`;
};
const shadow = (e) =>
  e.effects.map((f) => `${f.x}px ${f.y}px ${f.blur}px ${f.spread}px ${f.colorVar ? `var(${cssName(f.colorVar)})` : rgba(f.color, f.alpha)}`).join(", ") || "none";
const effectCss = (name) => "--shadow-" + name.toLowerCase().replace(/[\s/]+/g, "-");

const font = `"${src.fontFamily}", ui-sans-serif, system-ui, sans-serif`;
const overline = src.textStyles.find((t) => t.name === "Label/Overline");

// ---------- tokens.css ----------
let tokens = header + `/* Theme rules: light by default; dark when the device prefers dark, unless <html class="light">.
   class="dark" / class="light" on any element forces that theme for its subtree. */\n\n`;
tokens += block(":root", [
  "  /* Primitives — never use directly in components; use the semantic tokens below. */",
  ...prim.variables.map((v) => decl(v, v.values.Value)),
  "",
  `  --font-family-sans: ${font};`,
  `  --type-overline-size: ${overline.size}px;`,
  `  --type-overline-line-height: ${overline.lineHeight}px;`,
  ...src.effectStyles.map((e) => `  ${effectCss(e.name)}: ${shadow(e)}; /* ${e.description} */`),
  "",
  "  /* Responsive — Mobile (default) */",
  ...resp.variables.map((v) => decl(v, v.values.Mobile)),
  "",
  "  /* Semantic colour — Light */",
  "  color-scheme: light;",
  ...lightLines,
]);
tokens += `\n@media (min-width: ${bp.Tablet}px) {\n${indent(block(":root", ["  /* Responsive — Tablet */", ...resp.variables.map((v) => decl(v, v.values.Tablet))]))}}\n`;
tokens += `\n@media (min-width: ${bp.Desktop}px) {\n${indent(block(":root", ["  /* Responsive — Desktop */", ...resp.variables.map((v) => decl(v, v.values.Desktop))]))}}\n`;
tokens += `\n@media (prefers-color-scheme: dark) {\n${indent(block(":root:not(.light)", ["  color-scheme: dark;", ...darkLines]))}}\n`;
tokens += "\n" + block(".dark", ["  color-scheme: dark;", ...darkLines]);
tokens += "\n" + block(".light", ["  color-scheme: light;", ...lightLines]);

// ---------- tailwind-theme.css ----------
const semantic = color.variables.map((v) => `  --color-${v.css.replace(/^--color-/, "")}: ${cssValue(v, v.values.Light)};`);
const spaces = prim.variables.filter((v) => v.name.startsWith("space/")).map((v) => `  --spacing-${v.name.split("/")[1]}: var(${v.css});`);
const radii = prim.variables.filter((v) => v.name.startsWith("radius/")).map((v) => `  ${v.css}: ${cssValue(v, v.values.Value)};`);
const ls = (p) => (p ? `${p / 100}em` : "0em");
const textUtil = (key, sizeVar, weight, pct) => [
  `  --text-${key}: var(--${sizeVar.replace("/", "-")}-size);`,
  `  --text-${key}--line-height: var(--${sizeVar.replace("/", "-")}-line-height);`,
  `  --text-${key}--font-weight: ${weight};`,
  `  --text-${key}--letter-spacing: ${ls(pct)};`,
];
const ts = (n) => src.textStyles.find((t) => t.name === n);
const textMap = [
  ["display", "Display/Regular"], ["h1", "Heading/H1"], ["h2", "Heading/H2"], ["h3", "Heading/H3 Bold"],
  ["body-lg", "Body/Large Regular"], ["body", "Body/Regular"], ["body-sm", "Body/Small Regular"], ["caption", "Caption/Regular"],
  ["link", "Link/Default"], ["link-sm", "Link/Small"], ["label-button", "Label/Button"], ["label-tag", "Label/Tag"],
];
let theme = header + `/* Tailwind v4 theme. Default Tailwind colours, spacing numbers, radii, fonts, shadows and breakpoints are
   switched OFF so only Kieran's tokens exist as utilities. Numbers are pixels: p-16 = 16px = space/16.
   Real values live in tokens.css (unlayered, so it wins over this layer and handles dark + responsive). */\n\n`;
theme += block("@theme", [
  "  --color-*: initial;",
  "  --spacing: initial; /* turns off Tailwind's ×4 number scale (p-4 = 16px) */",
  "  --spacing-*: initial;",
  "  --radius-*: initial;",
  "  --font-*: initial;",
  "  --text-*: initial;",
  "  --shadow-*: initial;",
  "  --ease-*: initial;",
  "  --breakpoint-*: initial;",
  "  --container-*: initial;",
  "",
  "  /* Colours: bg-surface-default, text-text-secondary, border-border-strong, … */",
  ...semantic,
  "",
  "  /* Spacing: p-16, gap-8, mt-section, px-margin, gap-gutter, … */",
  ...spaces,
  "  --spacing-section: var(--space-section);",
  "  --spacing-section-sm: var(--space-section-sm);",
  "  --spacing-card-padding: var(--space-card-padding);",
  "  --spacing-card-gap: var(--space-card-gap);",
  "  --spacing-margin: var(--layout-margin);",
  "  --spacing-gutter: var(--layout-gutter);",
  "",
  "  /* Max widths: max-w-content, max-w-reading */",
  "  --container-content: var(--layout-content-width);",
  "  --container-reading: var(--layout-reading-width);",
  "",
  "  /* Radius: rounded-sm (4), rounded-md (8), rounded-lg (16), rounded-xl (20), rounded-full, rounded-card */",
  ...radii,
  "  --radius-card: var(--radius-card);",
  "",
  "  /* Font */",
  `  --font-sans: ${font};`,
  "",
  "  /* Type: text-h1, text-body, text-label-button, … (size + line height + weight + tracking, responsive) */",
  ...textMap.flatMap(([k, n]) => textUtil(k, ts(n).sizeVar, ts(n).weight, ts(n).letterSpacingPercent)),
  `  --text-overline: var(--type-overline-size);`,
  `  --text-overline--line-height: var(--type-overline-line-height);`,
  `  --text-overline--font-weight: ${overline.weight};`,
  `  --text-overline--letter-spacing: ${ls(overline.letterSpacingPercent)};`,
  "",
  "  /* Shadows: shadow-elevation-hover, shadow-focus-ring */",
  ...src.effectStyles.filter((e) => e.effects.length).map((e) => `  ${effectCss(e.name)}: ${shadow(e)};`),
  "",
  "  /* Easing: ease-out (springs are for JS animation libraries — see --motion-spring-*) */",
  "  --ease-out: var(--motion-ease-out);",
  "",
  "  /* Breakpoints: tablet:…, desktop:… (match Figma's Responsive modes) */",
  `  --breakpoint-tablet: ${bp.Tablet}px;`,
  `  --breakpoint-desktop: ${bp.Desktop}px;`,
]);

mkdirSync(resolve(root, "src/styles"), { recursive: true });
writeFileSync(resolve(root, "src/styles/tokens.css"), tokens);
writeFileSync(resolve(root, "src/styles/tailwind-theme.css"), theme);
console.log(`tokens.css: ${tokens.split("\n").length} lines · tailwind-theme.css: ${theme.split("\n").length} lines`);
